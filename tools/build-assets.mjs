/* tools/build-assets.mjs
 *
 * 构建期把本地资源转成 JS 包装文件，并生成两个运行时钩子（fetch shim +
 * THREE.DefaultLoadingManager.setURLModifier），让 file:// 双击产物在断网时
 * 也能加载贴图 / 音频 / 模型。只产出构建产物，绝不改写任何游戏源码。
 *
 *   import { buildAssetLayer } from './build-assets.mjs';
 *   const r = buildAssetLayer({ srcDir, dstDir, gameId, roots: ['public', 'assets'] });
 *   // r.scripts     -> 按顺序注入 <script src="..."> 的相对路径
 *   // r.inlineShim  -> 包进 <script> 注入到 bundle 之前的完整 JS 代码字符串
 *
 * CLI:
 *   node tools/build-assets.mjs --src=<dir> --out=<dstDir> [--game=<id>] [--check]
 *   --check 只统计不写文件；失败一律 exit(1)。
 *
 * 纪律：所有生成文件用 LF；base64→Uint8Array 在浏览器侧用 atob（不用 Buffer）；
 *       只写 dstDir，绝不触碰 srcDir 与仓库其它文件。
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ALLOWED_EXT = new Set([
  '.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg',
  '.mp3', '.ogg', '.wav', '.m4a',
  '.fbx', '.glb', '.gltf', '.bin', '.json', '.ktx2', '.hdr',
]);
const EXCLUDED_EXT = new Set(['.js', '.mjs', '.css', '.html', '.map', '.md']);
const EXCLUDED_DIRS = new Set(['vendor', 'node_modules', '.git']);
const IMAGE_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg']);
const MIME = {
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.webp': 'image/webp', '.gif': 'image/gif', '.svg': 'image/svg+xml',
  '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.wav': 'audio/wav', '.m4a': 'audio/mp4',
  '.fbx': 'application/octet-stream', '.glb': 'model/gltf-binary',
  '.gltf': 'model/gltf+json', '.bin': 'application/octet-stream',
  '.json': 'application/json', '.ktx2': 'image/ktx2', '.hdr': 'image/vnd.radiance',
};
const SIX_MB = 6 * 1024 * 1024;
const FOUR_MB = 4 * 1024 * 1024;

const SYNC_REL = 'vendor/__mg_assets_sync.js';
const MAP_REL = 'vendor/__mg_asset_map.js';
const ASSET_DIR_REL = 'vendor/__mg_assets';
const GENERATED = '/* generated by tools/build-assets.mjs - do not edit */';

function toPosix(p) { return p.split(path.sep).join('/'); }
function byteLen(s) { return Buffer.byteLength(s, 'utf8'); }

function walk(dir, out) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name.startsWith('.')) continue;          // 隐藏目录/文件
    const abs = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      if (EXCLUDED_DIRS.has(ent.name)) continue;
      walk(abs, out);
    } else if (ent.isFile()) {
      const ext = path.extname(ent.name).toLowerCase();
      if (EXCLUDED_EXT.has(ext)) continue;
      if (!ALLOWED_EXT.has(ext)) continue;
      out.push(abs);
    }
  }
}

function safeName(key) {
  const h = crypto.createHash('sha1').update(key).digest('hex').slice(0, 12);
  let base = key.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (base.length > 64) base = base.slice(0, 64);
  return base + '_' + h + '.js';
}

/* 生成 inlineShim：一段完整、幂等、IIFE 包裹的 classic JS 代码字符串。
 * 注意：本模板内刻意不出现反引号与 ${...}（除 roots 插值外），也不出现反斜杠，
 *       以便用普通模板字面量安全承载；反斜杠一律用 String.fromCharCode(92) 规避。 */
function buildShim(roots) {
  return `(function () {
  'use strict';
  /* 幂等：重复注入直接返回 */
  if (globalThis.__MG_SHIM_INSTALLED) return;
  globalThis.__MG_SHIM_INSTALLED = true;

  var G = globalThis;
  var W = (typeof window !== 'undefined' && window) ? window : G;
  var R = ${JSON.stringify(roots)};
  var PREFIX = '[mg-assets] ';

  function warn(msg) {
    try { if (typeof console !== 'undefined' && console.warn) console.warn(PREFIX + msg); } catch (e) {}
  }
  function defer(fn) {
    if (typeof queueMicrotask === 'function') return queueMicrotask(fn);
    if (typeof Promise !== 'undefined') return Promise.resolve().then(fn);
    return setTimeout(fn, 0);
  }

  /* 保存原生 fetch（覆盖之前） */
  var nativeFetch = null;
  try {
    var f = (typeof G.fetch === 'function') ? G.fetch : (typeof W.fetch === 'function' ? W.fetch : null);
    if (f) nativeFetch = f.bind(W);
  } catch (e) {}
  function callNative(input, init) {
    if (nativeFetch) return nativeFetch(input, init);
    if (W.fetch && W.fetch !== wrappedFetch) return W.fetch(input, init);
    return new Response(new Uint8Array(0), { status: 0 });
  }

  /* 从 fetch 入参提取 URL 字符串：支持 string / Request / URL / 带 href 的对象 */
  function toUrl(input) {
    if (typeof input === 'string') return input;
    if (input && typeof input === 'object') {
      if (typeof input.url === 'string') return input.url;
      if (typeof input.href === 'string') return input.href;
      if (typeof input.toString === 'function') {
        var s = input.toString();
        if (s && s !== '[object Object]') return s;
      }
    }
    return '';
  }

  /* 归一化 URL -> 候选 key 数组：
   *   去掉 query/hash、file:// 与 http(s)://host/ 前缀、前导 / 与 ./、处理 ../；
   *   候选 = 原样、去掉 public/ 前缀、按 public/assets 根切出的尾部路径、basename。
   *   绝对路径（file:///D:/.../public/assets/...）靠「根切分」还原成规范 key。 */
  function normalizeKey(url) {
    var out = [];
    function push(k) { if (k && out.indexOf(k) === -1) out.push(k); }
    var s = String(url);
    s = s.split('#')[0].split('?')[0];
    s = s.split(String.fromCharCode(92)).join('/');
    var schemeIdx = s.indexOf('://');
    if (schemeIdx > 0) {
      var scheme = s.slice(0, schemeIdx).toLowerCase();
      var rest = s.slice(schemeIdx + 3);
      if (scheme === 'http' || scheme === 'https') {
        var sl = rest.indexOf('/');
        s = sl >= 0 ? rest.slice(sl + 1) : '';
      } else {
        s = rest;
      }
    }
    s = s.replace(/^[/]+/, '');
    var parts = s.split('/');
    var stack = [];
    for (var i = 0; i < parts.length; i++) {
      var p = parts[i];
      if (p === '' || p === '.') continue;
      if (p === '..') { stack.pop(); continue; }
      stack.push(p);
    }
    var cleaned = stack.join('/');
    push(cleaned);
    if (cleaned.slice(0, 7) === 'public/') push(cleaned.slice(7));
    for (var r = 0; r < R.length; r++) {
      for (var t = 0; t < stack.length; t++) {
        if (stack[t] === R[r]) push(stack.slice(t).join('/'));
      }
    }
    push(stack[stack.length - 1]);
    return out;
  }

  function isImageUrl(u) {
    var c = String(u).split('#')[0].split('?')[0].toLowerCase();
    return /[.](png|jpe?g|webp|gif|svg)$/.test(c);
  }

  /* base64 -> Uint8Array：atob + 循环，浏览器里没有 Buffer */
  function base64ToBytes(b64) {
    var bin = atob(b64);
    var len = bin.length;
    var out = new Uint8Array(len);
    for (var i = 0; i < len; i++) out[i] = bin.charCodeAt(i);
    return out;
  }

  /* 动态 <script src> 懒加载；同一个 src 并发复用同一个 Promise */
  var scriptCache = Object.create(null);
  function loadScript(src) {
    if (scriptCache[src]) return scriptCache[src];
    var p = new Promise(function (resolve, reject) {
      try {
        var doc = G.document || (typeof document !== 'undefined' ? document : null);
        if (!doc || typeof doc.createElement !== 'function') { reject(new Error('no document')); return; }
        var el = doc.createElement('script');
        el.onload = function () { resolve(); };
        el.onerror = function () { reject(new Error('script load failed: ' + src)); };
        el.src = src;
        var parent = doc.head || doc.body || doc.documentElement;
        if (parent && typeof parent.appendChild === 'function') {
          try { parent.appendChild(el); } catch (e) {}
        }
      } catch (e) { reject(e); }
    });
    scriptCache[src] = p;
    return p;
  }

  function findValue(table, keys) {
    if (!table) return null;
    for (var i = 0; i < keys.length; i++) {
      var v = table[keys[i]];
      if (typeof v === 'string') return { key: keys[i], value: v };
    }
    return null;
  }

  var wrappedFetch = async function (input, init) {
    try {
      var method = (init && init.method) || (input && typeof input === 'object' && input.method) || 'GET';
      method = String(method).toUpperCase();
      if (method !== 'GET' && method !== 'HEAD') return callNative(input, init);
      var url = toUrl(input);
      if (!url) return callNative(input, init);
      if (/^(data|blob):/i.test(url)) return callNative(input, init);
      if (/^https?:/i.test(url)) return callNative(input, init); /* 外部 http(s) 不拦截 */
      var keys = normalizeKey(url);
      var hit = findValue(G.__MG_ASSET_MAP, keys);
      if (!hit) return callNative(input, init);
      await loadScript(hit.value);
      var A = G.__MG_ASSETS || {};
      var data = findValue(A, keys);
      if (!data) {
        /* 兜底：包装文件只写规范 key；按已加载脚本反查规范 key */
        var mapTbl = G.__MG_ASSET_MAP || {};
        for (var kk in A) {
          if (Object.prototype.hasOwnProperty.call(A, kk) && typeof A[kk] === 'string' && mapTbl[kk] === hit.value) {
            data = { key: kk, value: A[kk] };
            break;
          }
        }
      }
      if (!data) { warn('wrapper 未写入数据: ' + hit.value); return callNative(input, init); }
      var bytes = base64ToBytes(data.value);
      var mime = (G.__MG_ASSET_MIME && (G.__MG_ASSET_MIME[data.key] || G.__MG_ASSET_MIME[hit.key])) || 'application/octet-stream';
      return new Response(bytes, { status: 200, headers: { 'content-type': mime } });
    } catch (e) {
      warn('fetch shim 异常，回退原生 fetch: ' + (e && e.message));
      return callNative(input, init);
    }
  };

  try {
    G.fetch = wrappedFetch;
    if (W !== G) W.fetch = wrappedFetch;
  } catch (e) { warn('fetch 覆盖失败: ' + (e && e.message)); }

  /* URLModifier（同步）：图片类 URL 查 __MG_ASSET_DATA 返回 data URI */
  function resolveImage(url) {
    try {
      if (!isImageUrl(url)) return null;
      var hit = findValue(G.__MG_ASSET_DATA, normalizeKey(url));
      if (hit) return hit.value;
      /* 绝对 file:// URL 归一化后仍带完整盘符路径，与表里的规范 key 不同。
         做一次后缀匹配兜底（图片表通常只有几张，成本可忽略）。 */
      var cands = normalizeKey(url);
      var keys = Object.keys(G.__MG_ASSET_DATA || {});
      for (var i = 0; i < keys.length; i++) {
        for (var j = 0; j < cands.length; j++) {
          var c = String(cands[j] || '');
          if (!c) continue;
          if (keys[i] === c || keys[i].endsWith('/' + c) || c.endsWith('/' + keys[i])) {
            return G.__MG_ASSET_DATA[keys[i]];
          }
        }
      }
      return null;
    } catch (e) { warn('URLModifier 异常: ' + (e && e.message)); return null; }
  }
  function imageModifier(url) { return resolveImage(url) || url; }

  /* 决定性兜底：three 的 ImageLoader 最终必然执行 image.src = url，
     且默认 crossOrigin='anonymous'，file:// 下必然被 CORS 拦。
     无论业务 manager / loader 怎么绕，直接拦 HTMLImageElement.prototype.src，
     把命中资源表的图片 URL 换成 data URI（未命中的完全原样放行）。 */
  try {
    if (typeof HTMLImageElement !== 'undefined') {
      var imgProto = HTMLImageElement.prototype;
      var srcDesc = Object.getOwnPropertyDescriptor(imgProto, 'src');
      if (srcDesc && srcDesc.get && srcDesc.set && !imgProto.__mgSrcPatched) {
        Object.defineProperty(imgProto, 'src', {
          configurable: true, enumerable: srcDesc.enumerable,
          get: function () { return srcDesc.get.call(this); },
          set: function (v) {
            var mapped = v;
            try { mapped = imageModifier(String(v)); } catch (e) {}
            return srcDesc.set.call(this, mapped);
          }
        });
        imgProto.__mgSrcPatched = true;
      }
    }
  } catch (e) { warn('img.src 兜底失败: ' + (e && e.message)); }

  var installed = false;
  function installModifier() {
    if (installed) return true;
    try {
      var T = G.THREE;
      if (!T) return false;
      var combine = function (origSet, self, fn) {
        return origSet.call(self, function (url) {
          var mapped = imageModifier(url);
          if (mapped !== url) return mapped;
          if (typeof fn === 'function') { try { return fn(url); } catch (e) {} }
          return url;
        });
      };
      /* 1) TextureLoader 默认走 DefaultLoadingManager */
      var def = T.DefaultLoadingManager;
      if (def && typeof def.setURLModifier === 'function' && !def.__mgHooked) {
        var origDefSet = def.setURLModifier;
        var prevDef = def.urlModifier;
        def.setURLModifier = function (fn) { return combine(origDefSet, def, fn); };
        def.setURLModifier(prevDef);
        def.__mgHooked = true;
      }
      /* 2) 自定义 manager：three 的 setURLModifier 是**实例方法**，不在 prototype 上，
            prototype patch 无效。必须包一层构造函数，让每个 new THREE.LoadingManager()
            产出的实例都把「图片→data URI」前置到业务 modifier 之前。 */
      if (typeof T.LoadingManager === 'function' && !T.LoadingManager.__mgWrapped) {
        var OrigLM = T.LoadingManager;
        var WrappedLM = function () {
          var m = new OrigLM();
          try {
            var origSet = m.setURLModifier;
            if (typeof origSet === 'function') {
              m.setURLModifier = function (fn) { return combine(origSet, m, fn); };
            }
          } catch (e) {}
          return m;
        };
        WrappedLM.prototype = OrigLM.prototype;
        WrappedLM.__mgWrapped = true;
        T.LoadingManager = WrappedLM;
      }
      /* 3) 最终兜底：TextureLoader 内部必经 ImageLoader.prototype.load。
            无论业务 manager 如何覆盖 modifier，都在这里把图片 URL 换成 data URI。 */
      try {
        var IL = T.ImageLoader;
        if (IL && IL.prototype && typeof IL.prototype.load === 'function' && !IL.prototype.__mgImgPatched) {
          var origLoad = IL.prototype.load;
          IL.prototype.load = function (url, onLoad, onProgress, onError) {
            return origLoad.call(this, imageModifier(url), onLoad, onProgress, onError);
          };
          IL.prototype.__mgImgPatched = true;
        }
      } catch (e) { warn('ImageLoader 兜底失败: ' + (e && e.message)); }
      installed = true;
      return true;
    } catch (e) { warn('注册 URLModifier 失败: ' + (e && e.message)); return false; }
  }

  /* 诊断入口：产物里可手动调用，确认 URL → data URI 的匹配是否正常 */
  try { G.__mgDebugResolveImage = resolveImage; } catch (e) {}
  try { G.__mgDebugInstalled = function () { return installed; }; } catch (e) {}

  if (!installModifier()) {
    /* THREE 可能在本 shim 之后才由 three.classic.js 定义：装一个延迟钩子 */
    try {
      var cur = G.THREE;
      Object.defineProperty(G, 'THREE', {
        configurable: true, enumerable: true,
        get: function () { return cur; },
        set: function (v) {
          cur = v;
          try { installModifier(); } catch (e) {}
          defer(function () { try { installModifier(); } catch (e) {} });
        }
      });
    } catch (e) { warn('THREE 延迟钩子安装失败: ' + (e && e.message)); }
  }

  /* 兜底初始化各表（用 || 保证不覆盖同步脚本/映射脚本已写入的数据） */
  try {
    G.__MG_ASSETS = G.__MG_ASSETS || Object.create(null);
    G.__MG_ASSET_DATA = G.__MG_ASSET_DATA || Object.create(null);
    G.__MG_ASSET_MAP = G.__MG_ASSET_MAP || Object.create(null);
    G.__MG_ASSET_MIME = G.__MG_ASSET_MIME || Object.create(null);
  } catch (e) { warn('表初始化失败: ' + (e && e.message)); }
})();
`;
}

/* 扫描 + 计算全部产物内容（纯内存，不写盘） */
function computePlan(srcDir, roots, gameId) {
  if (!srcDir || !fs.existsSync(srcDir) || !fs.statSync(srcDir).isDirectory()) {
    throw new Error('srcDir 不存在或不是目录: ' + srcDir);
  }
  const warnings = [];
  const seen = new Set();
  const assets = [];
  for (const root of roots) {
    const rootAbs = path.join(srcDir, root);
    if (!fs.existsSync(rootAbs) || !fs.statSync(rootAbs).isDirectory()) continue;
    const found = [];
    walk(rootAbs, found);
    for (const abs of found) {
      const key = toPosix(path.relative(srcDir, abs));
      if (seen.has(key)) continue;
      seen.add(key);
      const ext = path.extname(abs).toLowerCase();
      const size = fs.statSync(abs).size;
      if (size > SIX_MB) warnings.push('单文件 > 6MB: ' + key + ' (' + size + ' B) - 仍处理');
      const b64 = fs.readFileSync(abs).toString('base64');
      assets.push({
        key, ext, size, b64,
        mime: MIME[ext] || 'application/octet-stream',
        isImage: IMAGE_EXT.has(ext),
        basename: key.split('/').pop(),
        wrapperPath: ASSET_DIR_REL + '/' + safeName(key),
      });
    }
  }
  assets.sort((a, b) => a.key.localeCompare(b.key));

  const fileCount = assets.length;
  if (fileCount === 0) {
    return {
      files: [], shim: '', scripts: [],
      stats: { fileCount: 0, syncBytes: 0, asyncCount: 0, totalBytes: 0, warnings },
    };
  }

  const mapMap = Object.create(null);   // __MG_ASSET_MAP: key -> wrapper 路径
  const mimeMap = Object.create(null);  // __MG_ASSET_MIME: key -> mime
  const dataMap = Object.create(null);  // __MG_ASSET_DATA: 仅规范 key（避免 base64 在别名里重复膨胀同步脚本）
  function addAlias(k, a) {
    mapMap[k] = a.wrapperPath;
    mimeMap[k] = a.mime;
  }
  for (const a of assets) {
    addAlias(a.key, a);
    /* 图片数据只写一次：normalizeKey 一定会产出规范 key，URLModifier 能命中 */
    if (a.isImage) dataMap[a.key] = 'data:' + a.mime + ';base64,' + a.b64;
    const stripped = a.key.startsWith('public/') ? a.key.slice(7) : null;
    if (stripped) addAlias(stripped, a);          // 去掉 public/ 前缀
    addAlias('./' + a.key, a);                    // ./ 前缀
    if (stripped) addAlias('./' + stripped, a);
  }
  /* basename 兜底：仅当全局唯一时注册，避免歧义命中 */
  const bnCount = Object.create(null);
  for (const a of assets) bnCount[a.basename] = (bnCount[a.basename] || 0) + 1;
  const bnWarned = new Set();
  for (const a of assets) {
    if (bnCount[a.basename] === 1) addAlias(a.basename, a);
    else if (!bnWarned.has(a.basename)) {
      bnWarned.add(a.basename);
      warnings.push('basename 重复，跳过该 basename 别名: ' + a.basename);
    }
  }

  const files = [];
  /* 1) 每个资源一个 JS 包装文件 */
  for (const a of assets) {
    const content = GENERATED + '\n' +
      'globalThis.__MG_ASSETS[' + JSON.stringify(a.key) + '] = ' + JSON.stringify(a.b64) + ';\n';
    files.push({ rel: a.wrapperPath, content });
  }
  /* 2) 图片同步脚本（URLModifier 同步查表用） */
  const syncContent = GENERATED + '\n' +
    'globalThis.__MG_ASSET_DATA = ' + JSON.stringify(dataMap, null, 2) + ';\n';
  files.push({ rel: SYNC_REL, content: syncContent });
  /* 3) 资源映射脚本 */
  const mapContent = GENERATED + '\n' +
    'globalThis.__MG_ASSETS = globalThis.__MG_ASSETS || {};\n' +
    'globalThis.__MG_ASSET_MAP = ' + JSON.stringify(mapMap, null, 2) + ';\n' +
    'globalThis.__MG_ASSET_MIME = ' + JSON.stringify(mimeMap, null, 2) + ';\n';
  files.push({ rel: MAP_REL, content: mapContent });

  const syncBytes = byteLen(syncContent);
  let totalBytes = 0;
  for (const f of files) totalBytes += byteLen(f.content);

  const imageRawTotal = assets.filter((a) => a.isImage).reduce((n, a) => n + a.size, 0);
  if (imageRawTotal > FOUR_MB || syncBytes > FOUR_MB) {
    warnings.push('图片数据量偏大: 原始 ' + imageRawTotal + ' B / 同步脚本 ' + syncBytes +
      ' B（> 4MB），首屏同步脚本较重');
  }

  return {
    files,
    shim: buildShim(roots),
    scripts: [SYNC_REL, MAP_REL],
    stats: {
      fileCount,
      syncBytes,
      asyncCount: fileCount,   // 每个资源一个按需懒加载的 JS 包装文件
      totalBytes,
      warnings,
      imageRawTotal,
      imageCount: assets.filter((a) => a.isImage).length,
      nonImageCount: assets.filter((a) => !a.isImage).length,
    },
  };
}

function writeFiles(dstDir, files) {
  for (const f of files) {
    const abs = path.join(dstDir, f.rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, f.content, 'utf8'); // 仅 LF
  }
}

export function buildAssetLayer({ srcDir, dstDir, gameId, roots = ['public', 'assets'], write = true } = {}) {
  const plan = computePlan(srcDir, roots, gameId);
  const s = plan.stats;
  if (write && s.fileCount > 0) writeFiles(dstDir, plan.files);
  return {
    scripts: plan.scripts,
    inlineShim: plan.shim,
    syncBytes: s.syncBytes,
    asyncCount: s.asyncCount,
    totalBytes: s.totalBytes,
    fileCount: s.fileCount,
    warnings: s.warnings,
  };
}

