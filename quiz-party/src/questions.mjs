/* 组装成对象数组。 */
export const QUESTIONS = RAW.map(function (r) {
  return { id: r[0], cat: r[1], q: r[2], o: r[3], a: r[4], e: r[5] };
});

/* id → 题目 的查表。 */
const BY_ID = Object.create(null);
for (const item of QUESTIONS) BY_ID[item.id] = item;

/** 按 id 取题；找不到返回 null。 */
export function questionById(id) {
  return BY_ID[id] || null;
}

/** 取某个分类的题目列表；cat 为 'all' 或未知分类时返回全部。 */
export function questionsOf(cat) {
  if (!cat || cat === 'all' || CATEGORY_LIST.indexOf(cat) < 0) return QUESTIONS.slice();
  return QUESTIONS.filter(function (item) { return item.cat === cat; });
}

/** 题库统计：每个分类各有多少题。 */
export function questionCounts() {
  const out = { all: QUESTIONS.length };
  for (const c of CATEGORY_LIST) {
    out[c] = QUESTIONS.filter(function (item) { return item.cat === c; }).length;
  }
  return out;
}
